#!/usr/bin/env python3
"""Generate the VQL of the CSV base views (DF datasource + wrapper + typed base view)
from data/*.csv. Writes platform/10_music_staging.vql, platform/12_sales_staging.vql
and governance/10_security_staging.vql. Column types (int / decimal / text) are
inferred from the data.

    python gen_csv_vql.py        # re-run after any change to a CSV file

The file path is written as the `@DATA_DIR@` placeholder, replaced by run_demo.py with
the absolute path of data/ at deploy time: the repository can live anywhere.
Datasources and wrappers use CREATE OR REPLACE, so moving the repository and
re-deploying re-points them (a plain CREATE would keep the old path, silently).

I18N us_pst: '.' as decimal separator, required for unit_price / cost_price
('fr' would read '1.29' as 1).

Folders follow a numbered convention shared with the dbt projects: 10 Datasources and
20 Base views here, 30/40/50 written by dbt. Position of the FOLDER clause, verified
live (VDP 9.4.7):
  - CREATE DATASOURCE DF <n> FOLDER = '...' ROUTE ...         (right after the name)
  - CREATE WRAPPER DF <n>    FOLDER = '...' DATASOURCENAME=...  (right after the name)
  - CREATE OR REPLACE TABLE <n> I18N x ( cols ) FOLDER = '...'  (AFTER the column list)
FOLDER before the column list of a CREATE TABLE, `ALTER TABLE ... FOLDER =` and
`ALTER VIEW ... FOLDER =` are parse errors: to move an object, re-create it.
"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
PLATFORM = os.path.join(HERE, "platform")       # datasources + base views of the domains
GOVERNANCE = os.path.join(HERE, "governance")   # identity mappings
FOLDER_DS = "/10 Datasources"    # datasources + wrappers
FOLDER_BV = "/20 Base views"     # base views (30/40/50 are written by dbt)
INT_RE = re.compile(r"^-?\d+$")
DEC_RE = re.compile(r"^-?\d+(\.\d+)?$")


def infer(values):
    vals = [v for v in values if v != ""]
    if not vals:
        return "text"
    if all(INT_RE.match(v) for v in vals):
        return "int"
    if all(DEC_RE.match(v) for v in vals):
        return "decimal"
    return "text"


def read_cols(csv_name):
    with open(os.path.join(DATA, csv_name), newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    header, data = rows[0], rows[1:]
    types = [infer([r[i] for r in data if i < len(r)]) for i in range(len(header))]
    return header, types


def df_block(table):
    csv_name = f"{table}.csv"
    cols, types = read_cols(csv_name)
    ds = f"ds_{table}"
    schema = ",\n        ".join(f"{c} = '\"{c}\"'" for c in cols)
    typedecl = ",\n        ".join(f"{c}:{t}" for c, t in zip(cols, types))
    constraints = "\n             ".join(f"ADD {c} NOS ZERO ()" for c in cols)
    return f"""-- {table}  <- data/{csv_name}
CREATE OR REPLACE DATASOURCE DF {ds}
    FOLDER = '{FOLDER_DS}'
    ROUTE LOCAL 'LocalConnection' '@DATA_DIR@/{csv_name}' FILENAMEPATTERN = ''
    CHARSET = 'UTF-8' COLUMNDELIMITER = ',' ENDOFLINEDELIMITER = '\\n' HEADER = TRUE;

CREATE OR REPLACE WRAPPER DF {ds}
    FOLDER = '{FOLDER_DS}'
    DATASOURCENAME={ds}
    OUTPUTSCHEMA (
        {schema}
    );

CREATE OR REPLACE TABLE bv_{table} I18N us_pst (
        {typedecl}
    )
    FOLDER = '{FOLDER_BV}'
    CACHE OFF TIMETOLIVEINCACHE DEFAULT
    ADD SEARCHMETHOD {ds} (
        I18N us_pst
        CONSTRAINTS (
             {constraints}
        )
        OUTPUTLIST ({', '.join(cols)})
        WRAPPER (df {ds})
    );
"""


# Staging and internal layers, NEVER exposed to consumers: datasources + base views only.
# The published views are built by dbt on top of them.
# file -> (folder, database, description, tables)
FILES = {
    "10_music_staging.vql": (PLATFORM, "chinook_music_staging",
                             "raw layer of the catalogue, NOT exposed (no consumer access)",
                             ["label", "artist", "album", "track"]),
    "12_sales_staging.vql": (PLATFORM, "chinook_sales_staging",
                             "raw layer of the sales, NOT exposed (no consumer access)",
                             ["customer", "invoice", "invoice_line"]),
    "10_security_staging.vql": (GOVERNANCE, "chinook_security_staging",
                                "identity mappings (login -> labels / customers), internal, never exposed",
                                ["buyer_label", "salesrep_customer"]),
}

if __name__ == "__main__":
    for fname, (outdir, db, desc, tables) in FILES.items():
        parts = [
            f"-- {db}: {desc}.",
            "-- GENERATED by gen_csv_vql.py from data/*.csv. Do not edit by hand.",
            "-- Staging layer: DF/CSV datasources + typed base views (I18N us_pst).",
            "-- @DATA_DIR@ is replaced by run_demo.py with the absolute path of data/.",
            f"CONNECT DATABASE {db};",
            "",
            f"CREATE OR REPLACE FOLDER '{FOLDER_DS}';",
            f"CREATE OR REPLACE FOLDER '{FOLDER_BV}';",
            "",
        ]
        parts += [df_block(t) for t in tables]
        with open(os.path.join(outdir, fname), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(parts))
        print(f"wrote {fname} ({len(tables)} CSV base views, not exposed)")
